// Raster icons (contentstack, quivers) — symbol is white on dark bg,
// so a CSS hue-shift to blue is sufficient
function RasterIcon({ hovered: h, size: sz, src }: P & { src: string }) {
  return (
    <img src={src} alt="" style={{
      width: sz, height: sz, display: "block",
      filter: h ? "hue-rotate(-46deg) saturate(0.85)" : undefined,
      transition: "filter 160ms ease",
    }} />
  )
}

const ICON_MAP: Record<string, React.FC<P>> = {
  "bc-logo":        BCIcon,
  "stripe-logo":    StripeIcon,
  "epicor-logo":    EpicorIcon,
  "epicore-logo":   EpicorIcon, // typo in k2.ts data
  "wordpress-logo": WordpressIcon,
}

export function DiagramIcon({ src, hovered, size }: { src: string; hovered: boolean; size: number }) {
  const filename = src.split("/").pop()?.replace(/\.(png|svg)$/, "") ?? ""
  const Component = ICON_MAP[filename]

  if (Component) return <Component hovered={hovered} size={size} />

  // Raster fallback (contentstack, quivers) — use SVG version
  const svgSrc = src
    .replace("/tool-icons/", "/tool-icons/svg/")
    .replace(".png", ".svg")
  return <RasterIcon hovered={hovered} size={size} src={svgSrc} />
}
